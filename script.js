// ========================================
// NASTAVENÍ HRY
// ========================================

const POCET_KOL = 8;

const VYCHOZI_LAT = 50.7671;
const VYCHOZI_LON = 15.0562;
const VYCHOZI_ZOOM = 13;


// ========================================
// PROMĚNNÉ HRY
// ========================================

let aktualniKolo = 1;
let celkoveSkore = 0;

let dostupnaMista = [...mista];

let misto = null;

let hracuvMarker = null;
let spravnyMarker = null;
let cara = null;

let odpovezeno = false;

let tipLat = null;
let tipLon = null;

let vysledkyKol = [];


// ========================================
// VYTVOŘENÍ MAPY
// ========================================

const map = L.map("map").setView(
    [VYCHOZI_LAT, VYCHOZI_LON],
    VYCHOZI_ZOOM
);

L.tileLayer("https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png", {
    attribution: "&copy; OpenStreetMap contributors"
}).addTo(map);


// ========================================
// NOVÉ KOLO
// ========================================

function noveKolo() {

    odpovezeno = false;

    tipLat = null;
    tipLon = null;


    if (dostupnaMista.length === 0) {
        dostupnaMista = [...mista];
    }


    const index = Math.floor(
        Math.random() * dostupnaMista.length
    );

    misto = dostupnaMista[index];

    dostupnaMista.splice(index, 1);


    // Zobrazíme fotografii
    document
        .getElementById("fotografie")
        .src = misto.foto;


    // Aktualizujeme číslo kola
    document
        .getElementById("kolo")
        .textContent =
        `Kolo ${aktualniKolo} / ${POCET_KOL}`;


    // Aktualizujeme skóre
    document
        .getElementById("celkoveSkore")
        .textContent =
        `${celkoveSkore.toLocaleString("cs-CZ")} bodů`;


    // Vrátíme mapu na Liberec
    map.setView(
        [VYCHOZI_LAT, VYCHOZI_LON],
        VYCHOZI_ZOOM
    );


    // Odstraníme staré značky
    if (hracuvMarker) {
        map.removeLayer(hracuvMarker);
        hracuvMarker = null;
    }

    if (spravnyMarker) {
        map.removeLayer(spravnyMarker);
        spravnyMarker = null;
    }

    if (cara) {
        map.removeLayer(cara);
        cara = null;
    }


    // Schováme výsledek
    document
        .getElementById("vysledek")
        .classList.add("skryty");


    // Zobrazíme potvrzení
    document
        .getElementById("potvrditTip")
        .classList.remove("skryty");
}


// ========================================
// KLIKNUTÍ NA MAPU
// ========================================

map.on("click", function (e) {

    if (odpovezeno) {
        return;
    }


    tipLat = e.latlng.lat;
    tipLon = e.latlng.lng;


    if (hracuvMarker) {
        map.removeLayer(hracuvMarker);
    }


    hracuvMarker = L.marker([
        tipLat,
        tipLon
    ]).addTo(map);
});


// ========================================
// POTVRZENÍ TIPU
// ========================================

document
    .getElementById("potvrditTip")
    .addEventListener("click", function () {

        if (tipLat === null || tipLon === null) {

            alert("Nejdříve klikni na mapu.");

            return;
        }


        odpovezeno = true;


        // Správné místo
        spravnyMarker = L.marker([
            misto.lat,
            misto.lng
        ]).addTo(map);


        // Spojovací čára
        cara = L.polyline([
            [tipLat, tipLon],
            [misto.lat, misto.lng]
        ]).addTo(map);


        // Vzdálenost
        const vzdalenost =
            spocitejVzdalenost(
                misto.lat,
                misto.lng,
                tipLat,
                tipLon
            );


        // Body
        const body =
            spocitejBody(vzdalenost);


        // Přidáme body
        celkoveSkore += body;

        vysledkyKol.push(body);


        // Zobrazíme výsledek
        document
            .getElementById("vzdalenost")
            .textContent =
            formatujVzdalenost(vzdalenost);


        document
            .getElementById("skore")
            .textContent =
            body.toLocaleString("cs-CZ");


        document
            .getElementById("celkoveSkore")
            .textContent =
            `${celkoveSkore.toLocaleString("cs-CZ")} bodů`;


        document
            .getElementById("vysledek")
            .classList.remove("skryty");


        // Schováme potvrzení
        document
            .getElementById("potvrditTip")
            .classList.add("skryty");


        // Přiblíží mapu na oba body
        map.fitBounds([
            [tipLat, tipLon],
            [misto.lat, misto.lng]
        ], {
            padding: [50, 50]
        });
    });


// ========================================
// DALŠÍ KOLO
// ========================================

document
    .getElementById("dalsiKolo")
    .addEventListener("click", function () {

        aktualniKolo++;


        if (aktualniKolo > POCET_KOL) {

            zobrazKonecHry();

            return;
        }


        noveKolo();
    });


// ========================================
// KONEC HRY
// ========================================

function zobrazKonecHry() {

    document
        .querySelector(".herni-plocha")
        .classList.add("skryty");


    document
        .getElementById("konecHry")
        .classList.remove("skryty");


    // Finální skóre
    document
        .getElementById("finalniSkore")
        .textContent =
        celkoveSkore.toLocaleString("cs-CZ");


    // Maximální skóre
    document
        .getElementById("maxSkore")
        .textContent =
        `/ ${POCET_KOL * 1000}`;


    // Průměr
    const prumer =
        Math.round(
            celkoveSkore / POCET_KOL
        );


    document
        .getElementById("prumerSkore")
        .textContent =
        prumer.toLocaleString("cs-CZ");


    // Přehled kol
    const prehled =
        document.getElementById("prehledKol");

    prehled.innerHTML = "";


    vysledkyKol.forEach(function (body, index) {

        const radek =
            document.createElement("div");

        radek.className = "prehled-kolo";

        radek.innerHTML = `
            <span>Kolo ${index + 1}</span>
            <strong>
                ${body.toLocaleString("cs-CZ")} bodů
            </strong>
        `;

        prehled.appendChild(radek);
    });
}


// ========================================
// NOVÁ HRA
// ========================================

document
    .getElementById("novaHra")
    .addEventListener("click", function () {

        aktualniKolo = 1;
        celkoveSkore = 0;
        vysledkyKol = [];

        dostupnaMista = [...mista];


        document
            .getElementById("konecHry")
            .classList.add("skryty");


        document
            .querySelector(".herni-plocha")
            .classList.remove("skryty");


        noveKolo();
    });


// ========================================
// VÝPOČET VZDÁLENOSTI
// ========================================

function spocitejVzdalenost(
    lat1,
    lon1,
    lat2,
    lon2
) {

    const R = 6371000;

    const radLat1 =
        lat1 * Math.PI / 180;

    const radLat2 =
        lat2 * Math.PI / 180;

    const rozdilLat =
        (lat2 - lat1) * Math.PI / 180;

    const rozdilLon =
        (lon2 - lon1) * Math.PI / 180;


    const a =
        Math.sin(rozdilLat / 2) ** 2 +
        Math.cos(radLat1) *
        Math.cos(radLat2) *
        Math.sin(rozdilLon / 2) ** 2;


    const c =
        2 * Math.atan2(
            Math.sqrt(a),
            Math.sqrt(1 - a)
        );


    return R * c;
}


// ========================================
// VÝPOČET BODŮ
// ========================================

function spocitejBody(vzdalenost) {

    // Do 50 metrů = plný počet
    if (vzdalenost <= 50) {
        return 1000;
    }


    // Od 5 km = nula
    if (vzdalenost >= 5000) {
        return 0;
    }


    // Plynulý pokles mezi 50 m a 5 km
    const body =
        1000 *
        Math.pow(
            1 - (vzdalenost - 50) / 4950,
            2
        );


    return Math.round(body);
}


// ========================================
// FORMÁTOVÁNÍ VZDÁLENOSTI
// ========================================

function formatujVzdalenost(vzdalenost) {

    if (vzdalenost < 1000) {

        return (
            Math.round(vzdalenost)
            + " m"
        );
    }


    return (
        (vzdalenost / 1000)
            .toFixed(2)
            .replace(".", ",")
        + " km"
    );
}


